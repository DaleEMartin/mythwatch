import Foundation
import MythwatchDomain

public struct HTTPRequest: Sendable, Equatable {
    public enum Method: String, Sendable { case get = "GET", post = "POST" }

    public var method: Method
    public var url: URL
    public var headers: [String: String]
    public var body: Data?

    public init(method: Method, url: URL, headers: [String: String] = [:], body: Data? = nil) {
        self.method = method
        self.url = url
        self.headers = headers
        self.body = body
    }
}

public struct HTTPResponse: Sendable {
    public var status: Int
    public var headers: [String: String]
    public var body: Data

    public init(status: Int, headers: [String: String] = [:], body: Data = Data()) {
        self.status = status
        self.headers = headers
        self.body = body
    }
}

public protocol HTTPTransport: Sendable {
    /// Throws `BackendError` only.
    func send(_ request: HTTPRequest) async throws -> HTTPResponse
}

/// Hook for `LoginUser` on newer backends.
public protocol RequestAuthorizer: Sendable {
    func authorize(_ request: HTTPRequest) async throws -> HTTPRequest
}
